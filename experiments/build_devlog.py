"""Concatenate the development-log entries into one file (P2-20).

    python -m experiments.build_devlog [--entries docs/devlog] [--out docs/devlog.md]

Each entry is one Markdown file `docs/devlog/YYYY-MM-DD-<member>-<slug>.md` that starts
with `# <title>` and has a `Date: YYYY-MM-DD` line. The entries are written in date
order (ties by file name) under a table of contents. Every heading of an entry is moved
one level down so the entries sit under the file's own title; fenced code blocks are
left unchanged. The output is generated: edit the entries, not `docs/devlog.md`.
"""
import argparse
import logging
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import List

from src.settings import repo_path

log = logging.getLogger(__name__)

DATE_LINE = re.compile(r"^\**Date:?\**:?\s*(\d{4}-\d{2}-\d{2})\s*$", re.MULTILINE)
HEADING = re.compile(r"^(#{1,5})(\s)")
FENCE = re.compile(r"^\s*(```|~~~)")


class DevlogError(ValueError):
    """An entry cannot be used (no title or no date)."""


@dataclass
class Entry:
    path: Path
    date: str
    title: str
    body: str

    @property
    def anchor(self) -> str:
        """A stable link target: the file name without `.md`."""
        return self.path.stem


def read_entry(path: Path) -> Entry:
    """Title (first `# ` line), date (`Date: YYYY-MM-DD` line) and the text after the title."""
    text = Path(path).read_text(encoding="utf-8").replace("\r\n", "\n")
    lines = text.split("\n")
    first = next((i for i, line in enumerate(lines) if line.strip()), None)
    if first is None or not lines[first].startswith("# "):
        raise DevlogError(f"{path}: the first line must be '# <title>'")
    m = DATE_LINE.search(text)
    if not m:
        raise DevlogError(f"{path}: no 'Date: YYYY-MM-DD' line")
    body = "\n".join(lines[first + 1:]).strip("\n")
    return Entry(Path(path), m.group(1), lines[first][2:].strip(), body)


def demote_headings(text: str) -> str:
    """Move every Markdown heading one level down, except inside fenced code blocks."""
    out, in_fence = [], False
    for line in text.split("\n"):
        if FENCE.match(line):
            in_fence = not in_fence
        elif not in_fence and HEADING.match(line):
            line = "#" + line
        out.append(line)
    return "\n".join(out)


def collect(entries_dir: Path) -> List[Entry]:
    """All entries of the folder, in date order (ties by file name)."""
    entries = [read_entry(p) for p in sorted(Path(entries_dir).glob("*.md"))]
    return sorted(entries, key=lambda e: (e.date, e.path.name))


def render(entries: List[Entry], entries_rel: str = "docs/devlog") -> str:
    """The whole log: title, generation note, table of contents and every entry."""
    parts = ["# Development log", "",
             f"Generated by `python -m experiments.build_devlog` from the {len(entries)} files in "
             f"`{entries_rel}/` (one file per entry). Edit those files and rerun the command; "
             "do not edit this file by hand.", "",
             "## Contents", ""]
    parts += [f"{i}. [{e.date} — {e.title}](#{e.anchor})" for i, e in enumerate(entries, 1)]
    for e in entries:
        parts += ["", "---", "", f'<a id="{e.anchor}"></a>', "", f"## {e.title}", "",
                  f"*Source: `{entries_rel}/{e.path.name}`*", "", demote_headings(e.body)]
    return "\n".join(parts).rstrip("\n") + "\n"


def build(entries_dir="docs/devlog", out="docs/devlog.md") -> List[Entry]:
    """Read the entries and write the combined log; returns the entries in output order."""
    entries = collect(repo_path(entries_dir))
    if not entries:
        raise DevlogError(f"no entries in {entries_dir}")
    Path(repo_path(out)).write_text(render(entries, Path(entries_dir).as_posix()), encoding="utf-8")
    return entries


def main(argv=None):
    ap = argparse.ArgumentParser(description="Concatenate docs/devlog/*.md into docs/devlog.md (P2-20).")
    ap.add_argument("--entries", default="docs/devlog")
    ap.add_argument("--out", default="docs/devlog.md")
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    entries = build(args.entries, args.out)
    log.info("%d entries written to %s", len(entries), args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
